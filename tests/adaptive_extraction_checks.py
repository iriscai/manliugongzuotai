"""No fixed count: model returns N=0/1/2/4, with source-owned evidence anchors."""
import csv,json,sys,tempfile,threading,time,copy
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'backend'))
from store import Store,dumps
from worker import Worker
from schemas import ADAPTIVE_EXTRACT,WRITE
from adaptive_extraction import source_segments,resolve_and_validate

CATS=['生活','教育','育儿','家居家装']
TOPICS=['图书角的开放时间','孩子轮流讲故事','家长记录孩子的问题','阅读区的空间布置']
BODY='社区图书角每天18时至20时开放。\n老师让孩子轮流讲故事。\n家长记录孩子的问题。\n阅读区用可移动书架划分空间，座椅留出通行距离。'
class Provider:
    def __init__(self,n,pause=False,bad=False,blocked=False):self.n=n;self.pause=pause;self.bad=bad;self.blocked=blocked;self.calls=[];self.worker=None;self.lock=threading.Lock()
    def auth_status(self,_):return {'ok':True}
    def call(self,prompt,schema,settings,folder,on_event=None):
        with self.lock:self.calls.append(('extract' if schema is ADAPTIVE_EXTRACT else 'write',prompt))
        time.sleep(.03)
        if schema is ADAPTIVE_EXTRACT:
            src=json.loads(prompt.split('\n统一输入素材：',1)[1]);segments=src['body']
            assert [x['text'] for x in segments]==BODY.splitlines()
            data={'categories':[{'category':CATS[i],'topic':TOPICS[i],'angle':TOPICS[i]+'的实际安排','reason':'按本类规则适配','main_point':segments[i]['text'],
                'elements':[{'name':'主题要素','content':segments[i]['text'],'evidence_ids':[segments[i]['id']]}],
                'omissions':[],'visual_nodes':['图书角'],'needs_verification':['核实活动安排'] if self.blocked and i==0 else [],'verified_additions':[]} for i in range(self.n)],'reason':'按素材实际内容判断'}
            if self.bad and self.n:data['categories'][0]['elements'][0]['evidence_ids']=['B_NOT_PRESENT']
        elif schema is WRITE:
            topic=prompt.split('本篇唯一主题：')[-1].splitlines()[0]
            data={'title':topic,'short_text':'图书角开放期间，孩子轮流讲故事，家长记录孩子的问题。阅读区留出通行空间。','frames':[{'number':1,'purpose':topic,'scene':'图书角','caption':'阅读活动','dialogue':[],'visible_labels':[],'image_prompt':'图书角示意图'}],'post_text':'','notice':'虚构功能测试','genre':'生活图解','adaptations':[]}
        else:raise AssertionError('Unexpected old extraction request')
        folder=Path(folder);folder.mkdir(parents=True,exist_ok=True);(folder/'answer.json').write_text(dumps(data),encoding='utf8')
        if schema is ADAPTIVE_EXTRACT and self.pause:self.pause=False;self.worker.pause()
        return data
    def terminate(self):pass

def seed(root):
    s=Store(root/'data',ROOT/'resources');s.save_settings({'allowed_categories':CATS,'process_workers':4,'write_workers':8})
    p=root/'input.csv'
    with p.open('w',encoding='utf8',newline='') as f:w=csv.writer(f);w.writerow(['标题','正文','分类']);w.writerow(['图书角活动安排',BODY,'生活'])
    s.import_file({'path':str(p)});return s
def run(s,p):w=Worker(s);w.provider=p;p.worker=w;r=w.start({'mode':'both','limit':1});w.thread.join(20);assert not w.thread.is_alive();return w,r

observed=[]
with tempfile.TemporaryDirectory(prefix='adaptive-extraction-') as tmp:
    root=Path(tmp)
    for n in [0,1,2,4]:
        s=seed(root/str(n));p=Provider(n);w,r=run(s,p);m=s.material(1)
        assert len(m['extractions'])==n and len(m['results'])==n
        assert sum(k=='extract' for k,_ in p.calls)==1 and sum(k=='write' for k,_ in p.calls)==n
        assert m['extraction_batches'][0]['target_count']==0
        pairs={(e['category'],e['topic']) for e in m['extractions']}
        written={(json.loads(x['data_json'])['category'],json.loads(x['data_json'])['topic']) for x in m['results']}
        assert pairs==written
        for e in m['extractions']:
            data=json.loads(e['data_json'])
            assert data['extraction_scheme']=='adaptive_topics_v1'
            for quote in data['evidence']:assert quote['quote'] in BODY
        observed.append({'model_selected_n':n,'extract_requests':1,'write_requests':n})
    s=seed(root/'pause');p=Provider(4,pause=True);w,r=run(s,p)
    assert s.stats()['runs'][0]['state']=='paused' and len(s.material(1)['extractions'])==4
    w.resume(r['run_id']);w.thread.join(20);assert len(s.material(1)['results'])==4 and sum(k=='extract' for k,_ in p.calls)==1
    s=seed(root/'blocked');p=Provider(4,blocked=True);w,r=run(s,p)
    assert len(s.material(1)['results'])==3 and s.stats()['writing']['needs_review']==1
    s=seed(root/'bad');p=Provider(2,bad=True);w,r=run(s,p)
    assert not s.material(1)['extractions'] and not s.material(1)['results'] and s.stats()['runs'][0]['errors']==1
    # Source slices are never generated by the model, including the exact phrase that failed live.
    source={'title':'测试','body':'我闺女把我行李提到门口，说车票我给您买好了，下午两点的。'}
    encoded,pool=source_segments(source);assert pool['B0001']['quote']==source['body'] and encoded['body'][0]['text']==source['body']
report={'ok':True,'observed':observed,'source_anchors_exact':True,'unknown_anchor_rejected_atomically':True,'topic_category_pairs_preserved':True,'verification_gate_preserved':True,'resume_reuses_extraction':True,'external_model_calls':0}
(ROOT/'build/adaptive-extraction-checks.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf8');print(dumps(report))
